# --------------------------------------------------------------------------- plumbing
RUNNER = r"""
const fs = require('fs'), vm = require('vm');
const src = fs.readFileSync(process.argv[1], 'utf8') +
  '\n;globalThis.__a = { evaluateAnswer, normaliseText, tokenise, _isContent, parseKeyTerms, matchKeyTerms, countWords, contentTokens, AM_LIMITS, STOPWORDS_BY_LANG };';
const ctx = { console }; vm.createContext(ctx); vm.runInContext(src, ctx);
const A = ctx.__a;
const lk = l => (String(l || 'en').toLowerCase().split(/[-_]/)[0] || 'en');
const jobs = JSON.parse(fs.readFileSync(0, 'utf8'));
// The key-term strings exactly as parseKeyTerms keeps them (same order, same cut-off), so index i of the
// per-term results below is index i of this list.
const aligned = kt => {
  const out = [];
  for (const s of (Array.isArray(kt) ? kt : [])) {
    if (out.length >= A.AM_LIMITS.MAX_KEY_TERMS) break;
    if (A.parseKeyTerms([s]).length) out.push(s);
  }
  return out;
};
// Same rule as evaluateAnswer: an author threshold wins; else 6 or 35% of the sample, whichever is smaller.
const minWordsFor = (j, lang) => {
  const th = j.shortAnswerThreshold;
  const o = (typeof th === 'number' || (typeof th === 'string' && th !== '')) ? parseInt(th, 10) : NaN;
  if (Number.isFinite(o)) return o;
  const s = typeof j.sampleAnswer === 'string' ? j.sampleAnswer.slice(0, A.AM_LIMITS.MAX_CONTEXT_CHARS) : '';
  return s ? Math.min(6, Math.round(A.countWords(s, lang) * 0.35)) : 6;
};
const out = jobs.map(j => {
  const lang = lk(j.lang);
  const stop = A.STOPWORDS_BY_LANG[lang];
  if (j.mode === 'meta') return { minWords: minWordsFor(j, lang) };
  if (j.mode === 'lint') {
    const terms = aligned(j.keyTerms);
    const text = (j.passage || '') + ' ' + (j.question || '');
    return { terms, anchored: terms.map(t => A.matchKeyTerms(text, A.parseKeyTerms([t]), lang).matched > 0),
             contentWords: A.contentTokens(j.passage || '', lang).length,
             stop: stop ? Array.from(stop) : [],
             forms: (j.forms || []).map(([i, f]) => A.matchKeyTerms(f, A.parseKeyTerms([terms[i]]), lang).matched > 0) };
  }
  if (j.mode === 'corpus') {          // share of the texts that each alternative matches
    const parsed = j.alts.map(a => A.parseKeyTerms([a]));
    return { rates: parsed.map(p => j.texts.length ? j.texts.filter(t => A.matchKeyTerms(t, p, lang).matched > 0).length / j.texts.length : 0) };
  }
  const r = A.evaluateAnswer(j);
  const terms = aligned(j.keyTerms);
  const parsed = A.parseKeyTerms(j.keyTerms);
  const hits = parsed.map(t => A.matchKeyTerms(j.answer, [t], lang).matched > 0);
  const limit = stop ? A.AM_LIMITS.RATIO_WITH_STOPWORDS : A.AM_LIMITS.RATIO_NO_STOPWORDS;
  const norm = A.normaliseText(j.answer);
  const toks = A.tokenise(norm, lang);
  const ratio = (list, set) => list.length ? list.filter(t => set.has(t)).length / list.length : 0;
  const pw = new Set();
  // measured against the real passage even when the author has skipped the copy check (j.passageTexts is then empty)
  for (const p of (j.measurePassageTexts || j.passageTexts || [])) for (const t of A.tokenise(A.normaliseText(p), lang)) if (A._isContent(t, lang, 2)) pw.add(t);
  const qw = new Set(A.tokenise(A.normaliseText(j.questionText || ''), lang).filter(t => A._isContent(t, lang, 2)));
  const total = parsed.length;
  return { code: r.code, matched: r.matched, total: r.total, hits, terms, limit,
           needed: total ? Math.max(Math.ceil(total / 2), Math.min(2, total)) : 0,
           minWords: minWordsFor(j, lang), words: A.countWords(j.answer, lang),
           passOverlap: ratio(toks.filter(t => A._isContent(t, lang, 2)), pw),
           qOverlap: ratio(toks.filter(t => A._isContent(t, lang, 1)), qw) };
});
process.stdout.write(JSON.stringify(out));
"""


def die(msg, code=2):
    print('ERROR ' + msg, file=sys.stderr); sys.exit(code)


def find_answer_match():
    here = os.path.dirname(os.path.abspath(__file__))
    for p in (os.environ.get('ANSWER_MATCH_JS'), os.path.join(here, '..', 'app', 'js', 'answer-match.js'),
              os.path.join(here, 'answer-match.js')):
        if p and os.path.isfile(p): return p
    return None


def run_node(jobs):
    if not jobs: return []
    path = find_answer_match()
    if not path: die('answer-match.js not found (put it next to this script, in ../app/js/, or set ANSWER_MATCH_JS); the test cannot run')
    if not shutil.which('node'): die('Node.js not found; the test cannot run')
    out = subprocess.run(['node', '-e', RUNNER, path], input=json.dumps(jobs), capture_output=True, text=True, timeout=600)
    try: return json.loads(out.stdout)
    except Exception: die('the matcher failed: ' + (out.stderr or out.stdout)[:400])


def plain(s):
    s = re.sub(r'\[\[sc:(.*?)\]\]', r'\1', str(s)); s = re.sub(r'\[\[icon:[A-Za-z0-9]*\]\]', '', s)
    s = re.sub(r'<[^>]+>', ' ', s); s = re.sub(r'\[([^\]]*)\]\([^)]*\)', r'\1', s); s = re.sub(r'[*_`]{1,3}', '', s)
    return re.sub(r'\s+', ' ', html.unescape(s)).strip()


def plain_passage(raw):
    s = re.sub(r'\[\[sc:(.*?)\]\]', r'\1', str(raw))
    s = re.sub(r'<sup\b[^>]*>\s*\d+[a-z]?\s*</sup>', ' ', s, flags=re.I)
    s = re.sub(r'<[^>]*>', ' ', s); s = html.unescape(s); s = re.sub(r'\b\d+(?=[a-zA-Z])', '', s)
    return re.sub(r'\s+', ' ', s).strip()


def load_study(path):
    try:
        if zipfile.is_zipfile(path):
            z = zipfile.ZipFile(path); name = next((n for n in z.namelist() if n.endswith('study.json')), None)
            if not name: die('zip has no study.json')
            return json.loads(z.read(name).decode('utf-8'))
        return json.load(open(path, encoding='utf-8'))
    except (OSError, ValueError) as e:
        die(f'cannot read {path}: {e}')


def field(e, name, slot):
    """The value the app reads for the active language slot: slot N, then slot 1, then the unnumbered field."""
    for k in ([name + slot, name + '1', name] if slot else [name]):
        v = e.get(k)
        if v is not None and v != '': return v
    return None


def questions(study, slot=''):
    """Questions that get the app's answer check and have key terms, with everything the check uses."""
    meta = study.get('studyMetadata') or {}
    multi = 'language1' in meta
    if multi and not slot: slot = '1'
    if slot and not multi: slot = ''
    lang = str(meta.get('language' + slot if slot else 'language') or 'en')
    out = []
    for ch in study.get('chapters') or []:
        passages = defaultdict(list)
        for e in ch.get('elements') or []:
            if e.get('type') == 'biblePassage':
                refs, texts = set(), []
                for k, v in e.items():
                    m = re.fullmatch(r'bibleRef(\d*)', k)
                    if m and v: refs.add(v)
                    m = re.fullmatch(r'passageText(\d*)', k)
                    if m and isinstance(v, str) and v.strip(): texts.append(plain_passage(v))
                for r in refs: passages[r] += texts          # the app compares with every translation
            elif e.get('type') == 'question':
                sub = e.get('subtype'); lp = field(e, 'linkedPassage', slot)
                # the app shows the check on any question that is not a header or reflection, and on any with a linkedPassage
                if sub in ('header', 'reflection') and not lp: continue
                kt = field(e, 'keyTerms', slot)
                if not kt: continue
                thr = field(e, 'shortAnswerThreshold', slot)
                out.append({'id': e['elementId'], 'chapter': ch.get('chapterNumber'), 'ref': lp or '',
                            'question': plain(field(e, 'question', slot) or ''), 'passages': passages.get(lp, []) if lp else [],
                            'hintFirst': plain(field(e, 'questionHintFirst', slot) or ''), 'hint': field(e, 'questionHint', slot) or '',
                            'sample': field(e, 'sampleAnswer', slot) or '', 'keyTerms': kt,
                            'mainPoint': field(e, 'mainPoint', slot), 'thr': thr,
                            'skip': e.get('skipBibleVerseCheck') is True or e.get('skipBibleVerseCheck') == 'true', 'lang': lang})
    return out


def job_base(q):
    # sampleAnswer goes in raw, as the app passes it (it does not strip markup before counting words)
    return {'questionText': q['question'], 'passageTexts': [] if q['skip'] else q['passages'], 'measurePassageTexts': q['passages'], 'sampleAnswer': q['sample'],
            'keyTerms': q['keyTerms'], 'lang': q['lang'], 'shortAnswerThreshold': q['thr'], 'skipBibleVerseCheck': q['skip']}


# --------------------------------------------------------------------------- lint
def candidate_forms(w):
    """Word forms a reader may use that a plain prefix of `w` would not match."""
    forms = set()
    if w in VERBS_E: forms.add(w[:-1] + 'ing')
    if w in VERBS_Y: forms |= {w[:-1] + 'ied', w[:-1] + 'ies'}
    forms |= set(IRREGULAR.get(w, [])) | set(DERIVED.get(w, []))
    return forms


def lint(qs):
    texts = [t for q in qs for t in (plain(q['sample']), plain(q['mainPoint'] or '')) if t]
    base = [{'mode': 'lint', 'passage': ' '.join(q['passages']), 'question': q['question'], 'keyTerms': q['keyTerms'], 'lang': q['lang']} for q in qs]
    first = run_node(base)
    stop = set(first[0]['stop']) if first else set()
    pairs = []          # per question: [(term index, form)] to test with the real matcher
    for r in first:
        p = []
        for i, term in enumerate(r['terms']):
            for a in term.split('|'):
                w = a.strip().lower()
                if re.fullmatch(r'[a-z]+', w):
                    for f in sorted(candidate_forms(w)): p.append([i, f])
        pairs.append(p)
    res = run_node([dict(b, forms=p) for b, p in zip(base, pairs)])
    alts = sorted({a.strip() for r in first for t in r['terms'] for a in t.split('|')
                   if a.strip() and not a.strip().endswith('$') and not a.strip().startswith('*')})
    rates = {}
    if texts and alts and len(qs) >= 10:     # too few questions to say what is "broad" for this study
        for a, rate in zip(alts, run_node([{'mode': 'corpus', 'alts': alts, 'texts': texts, 'lang': qs[0]['lang']}])[0]['rates']): rates[a] = rate
    near = {}           # overlap of the author's own sampleAnswer / mainPoint with the passage
    for label, get in (('sampleAnswer', lambda q: q['sample']), ('mainPoint', lambda q: q['mainPoint'] or '')):
        rr = run_node([dict(job_base(q), answer=plain(get(q)), shortAnswerThreshold=0) for q in qs])
        for q, x in zip(qs, rr):
            if plain(get(q)) and x['passOverlap'] >= NEAR_LIMIT and not q['skip']: near.setdefault(q['id'], []).append(f"{label} {round(x['passOverlap'] * 100)}%")
    findings = []
    for q, r, p, r2 in zip(qs, first, pairs, res):
        f = []; terms = r['terms']
        un = [t for t, ok in zip(terms, r['anchored']) if not ok]
        if len(un) >= 2:   # one synonym-only term is normal; two or more suggests the terms came from outside the passage on screen
            f.append(('unanchored', 'key terms that match nothing in the linked passage or the question (a reader answering from the passage on screen may never meet them): ' + '; '.join(f'`{t}`' for t in un)))
        missed = defaultdict(list)
        for (i, form), ok in zip(p, r2['forms']):
            if not ok: missed[i].append(form)
        for i, term in enumerate(terms):
            for a in term.split('|'):
                a = a.strip(); w = a.lower().lstrip('*').rstrip('$')
                if not w: continue
                exact = a.endswith('$'); inside = a.startswith('*')
                if (w in stop or len(w) <= 2) and not exact:
                    f.append(('generic', f'alternative `{a}` in `{term}` is a stopword or very short, so it will match almost any answer'))
                    continue
                if len(w) == 3 and re.fullmatch(r'[a-z]+', w) and not exact and not inside:
                    f.append(('shortStem', f'`{a}` in `{term}` is a 3-letter prefix: it also matches longer words that begin the same way (add `$` for the whole word, or use a longer stem)'))
                if a in rates and rates[a] >= BROAD_RATE and not exact and ' ' not in a:
                    f.append(('broad', f'`{a}` in `{term}` appears in {round(rates[a] * 100)}% of this study\'s own model answers, so it says little about this question'))
            if missed.get(i):
                forms = sorted(set(missed[i]))
                f.append(('form', f'`{term}` does not match {", ".join(chr(8220) + x + chr(8221) for x in forms)}: add {", ".join("`" + x + "`" for x in forms)} as alternatives (or use a stem of four or more letters)'))
        if len(terms) < 3: f.append(('coarse', f'only {len(terms)} key term(s); a single miss can change the result'))
        if r['contentWords'] <= TIGHT_PASSAGE_WORDS and not q['skip'] and q['passages']:
            f.append(('tightPassage', f'the linked passage has only {r["contentWords"]} content words, so a short correct answer can pass the 70% limit and be called a copy; write a `hugging` answer for it in the test. skipBibleVerseCheck would fix this but also stops copies of the passage being caught'))
        if q['id'] in near:
            f.append(('nearLimit', f"{', '.join(near[q['id']])} of the words are in the passage (the check calls it a copy above 70%): a reader who copies it, or a faithful short answer, may be told it repeats the passage"))
        if not q['mainPoint']: f.append(('missing', 'no mainPoint'))
        if not q['hintFirst']: f.append(('missing', 'no questionHintFirst'))
        findings.append((q, f))
    return findings


def print_lint(findings):
    n = sum(len(f) for _, f in findings); bad = [(q, f) for q, f in findings if f]
    print(f'LINT: {len(findings)} questions, {n} findings in {len(bad)} questions')
    print('  by kind:', dict(Counter(k for _, f in findings for k, _ in f)))
    for q, f in bad:
        print(f"  {q['id']} ({q['ref']})")
        for k, m in f: print(f'     [{k}] {m}')
    return n


# --------------------------------------------------------------------------- generated (automatic) weak answers
def term_candidates(q):
    """Per key term, its alternatives as plain words (no $ or *)."""
    out = []
    for t in (q['keyTerms'] if isinstance(q['keyTerms'], list) else []):
        if isinstance(t, str):
            c = [x.strip().lstrip('*').rstrip('$').strip() for x in t.split('|')]
            c = [x for x in c if x]
            if c: out.append(c)
    return out


def salad(cands, min_words):
    """One alternative per key term, then more alternatives round the terms until the answer is long enough to
    get past the minimum-words check: what someone typing key words at random would send."""
    if not cands: return ''
    words, k = [], 0
    while k < 12 and (k == 0 or len(' '.join(words).split()) < max(min_words, 1)):
        words += [c[k % len(c)] for c in cands[:12]]; k += 1
    return ' '.join(words)


def auto_answers(q, min_words, fresh=None):
    """Weak answers made from the study's own data: no writer needed, so they run on every question every time."""
    out = [('A1', 'filler', 'idk'), ('A2', 'filler', 'Not sure about this one.')]
    n = min(3, min_words - 1); words = q['sample'].split()
    if n >= 1 and len(words) >= n: out.append(('A3', 'fragment', ' '.join(words[:n])))
    if len(q['question']) > 25: out.append(('A4', 'echoQuestion', q['question']))
    if not q['skip']:
        for i, p in enumerate(q['passages']):
            if len(p) > 25: out.append(('A5' if i == 0 else f'A5.{i + 1}', 'passageCopy', p))
    cands = term_candidates(q)
    if cands: out.append(('A6', 'keySalad', salad(cands, min_words)))
    if cands and fresh is not None: out.append(('A7', 'keySaladFresh', salad(fresh, min_words)))
    return out


def judge_weak(kind, code):
    rule = KIND_RULES.get(kind)
    if not rule: return None, False
    ok = (code != 'strong') if rule['expect'] == 'NOT_STRONG' else (code in rule['expect'])
    return rule['tier'], ok


def fresh_salads(qs):
    """Per question: the key-term alternatives re-ordered so that those NOT found in the linked passage come first.
    A salad built from them has no sense and none of the passage's words, so it shows how far the key terms can be gamed."""
    jobs, cands = [], []
    for q in qs:
        c = term_candidates(q); cands.append(c)
        flat = sorted({x for t in c for x in t})
        jobs.append({'mode': 'corpus', 'alts': flat or ['x'], 'texts': [' '.join(q['passages'])] if q['passages'] else [''], 'lang': q['lang'], 'flat': flat})
    res = run_node(jobs); out = {}
    for q, c, j, r in zip(qs, cands, jobs, res):
        inpass = {a for a, rate in zip(j['alts'], r['rates']) if rate > 0}
        out[q['id']] = [[x for x in t if x not in inpass] + [x for x in t if x in inpass] for t in c]
    return out


def score_questions(qs, written):
    """written: {qid: {'strong': [...], 'weak': [...]}} (may be empty). Runs written + generated answers.
    Returns per-question dicts (items with results attached)."""
    metas = run_node([dict(job_base(q), mode='meta') for q in qs])
    fresh = fresh_salads(qs)
    items = []   # (qid, group, id, label, text, auto)
    for q, m in zip(qs, metas):
        w = written.get(q['id'], {})
        for a in w.get('strong', []): items.append((q['id'], 'strong', a['id'], a['style'], a['text'], False))
        for a in w.get('weak', []): items.append((q['id'], 'weak', a['id'], a['kind'], a['text'], False))
        for aid, kind, text in auto_answers(q, m['minWords'], fresh.get(q['id'])): items.append((q['id'], 'weak', aid, kind, text, True))
    byid = {q['id']: q for q in qs}
    res = run_node([dict(job_base(byid[i[0]]), answer=i[4]) for i in items])
    per = defaultdict(list)
    for it, r in zip(items, res):
        per[it[0]].append({'group': it[1], 'id': it[2], 'label': it[3], 'text': it[4], 'auto': it[5], 'r': r})
    return per


# --------------------------------------------------------------------------- answers file checks
def check_answers_file(answers, study_meta, qs_all, allow_incomplete, ignore_meta):
    """(problems, warnings, incomplete) for the answers file; problems make the test unusable (exit 2)."""
    problems, warnings, incomplete = [], [], {}
    am = answers.get('meta') or {}
    if not ignore_meta:
        if am.get('studyId') and study_meta.get('studyId') and am['studyId'] != study_meta['studyId']:
            problems.append(f"the answers are for study {am['studyId']!r}, not {study_meta['studyId']!r} (use --ignore-meta to override)")
        if am.get('studyVersion') is not None and study_meta.get('studyVersion') is not None and str(am['studyVersion']) != str(study_meta['studyVersion']):
            warnings.append(f"the answers were written for studyVersion {am['studyVersion']}; the study is {study_meta['studyVersion']}. Treat this as a regression run: it shows whether the old answers still behave as they did")
    if am.get('protocol') not in ('blind', 'semi-blind', 'example'):
        warnings.append(f"meta.protocol is {am.get('protocol')!r}: say whether the run was 'blind' or 'semi-blind'")
    byid = {q['id'] for q in qs_all}
    acc = am.get('accepted', [])
    if not isinstance(acc, list): problems.append('meta.accepted must be a list of {"question", "id", "reason"}'); acc = []
    for a in acc:
        if not isinstance(a, dict) or not a.get('question') or not a.get('id'):
            problems.append(f'meta.accepted: {a!r} needs "question" and "id"'); continue
        if not str(a.get('reason', '')).strip(): problems.append(f"meta.accepted {a['question']} {a['id']}: a reason is required (it is the record of the decision)")
        ids = {x.get('id') for x in ((answers.get('questions') or {}).get(a['question']) or {}).get('strong', [])}
        if a['id'] not in ids: problems.append(f"meta.accepted {a['question']} {a['id']}: only a written strong answer in the answers file can be accepted")
    need_strong = {s for _, s, _, _ in STRONG_STYLES}; need_weak = {k for _, k, _ in WRITTEN_WEAK}
    for qid, sets in (answers.get('questions') or {}).items():
        if qid not in byid: problems.append(f'{qid} is not a question with key terms that gets the answer check in this study'); continue
        seen = Counter(); weak_seen = Counter()
        for a in sets.get('strong', []):
            if not str(a.get('text', '')).strip(): problems.append(f"{qid} {a.get('id')}: empty answer text")
            if a.get('style') not in STRONG_ROLE: problems.append(f"{qid} {a.get('id')}: unknown strong style {a.get('style')!r}")
            seen[a.get('style')] += 1
        for a in sets.get('weak', []):
            if not str(a.get('text', '')).strip(): problems.append(f"{qid} {a.get('id')}: empty answer text")
            if a.get('kind') not in KIND_RULES: problems.append(f"{qid} {a.get('id')}: unknown weak kind {a.get('kind')!r}")
            weak_seen[a.get('kind')] += 1
        for s, n in seen.items():
            if n > 1 and s in STRONG_ROLE: problems.append(f'{qid}: strong style {s!r} appears {n} times (one answer per style)')
        missing = sorted(need_strong - set(seen)) + sorted(need_weak - set(weak_seen))
        if missing: incomplete[qid] = missing
    return problems, warnings, incomplete


def label_problems(per, byid):
    """Answers whose label does not fit what the answer measurably is (written answers only)."""
    out = []
    for qid, rows in per.items():
        for x in rows:
            if x['auto']: continue
            r = x['r']; k = x['label']; why = None
            if k == 'passageCopy' and r['passOverlap'] < 0.9: why = f"labelled a passage copy but only {round(r['passOverlap'] * 100)}% of its words are in the passage"
            elif k == 'echoQuestion' and r['qOverlap'] < 0.7: why = f"labelled a question echo but only {round(r['qOverlap'] * 100)}% of its words are in the question"
            elif k == 'filler' and r['words'] > 6: why = f"labelled filler but has {r['words']} words"
            elif k == 'fragment' and r['words'] > 4: why = f"labelled a fragment but has {r['words']} words"
            elif k in ('halfRight', 'misguided', 'offTopic') and r['passOverlap'] > r['limit']:
                why = (f"labelled {k} but {round(r['passOverlap'] * 100)}% of its words are in the passage, above the app's {round(r['limit'] * 100)}% limit: "
                       f"it is a copy of the passage, not a {k} answer (write it in your own words)")
            elif k == 'passageReword' and r['passOverlap'] < 0.4: why = f"labelled a passage reword but only {round(r['passOverlap'] * 100)}% of its words are in the passage (it is something else)"
            if why: out.append(f"{qid} {x['id']}: {why}")
    return out


