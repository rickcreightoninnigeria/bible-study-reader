    for q, m in zip(qs, metas):
        md += ['', f"## {q['id']} (session {q['chapter']}) · {q['ref']}", f"**Question:** {q['question']}", f"**Passage on screen:** {' / '.join(q['passages']) or '(none)'}",
               f"**Minimum words before the check stops saying \"too short\":** {m['minWords']}"]
